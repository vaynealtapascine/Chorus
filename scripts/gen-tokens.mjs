// Generate platform token files from design/tokens.json (DESIGN.md §1).
//   node scripts/gen-tokens.mjs           write them
//   node scripts/gen-tokens.mjs --check   fail if a committed file differs (verify.py)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const stale = [];
function emit(path, text) {
  if (check) {
    const now = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
    if (now !== text) stale.push(path);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}
const header = '/* Generated by scripts/gen-tokens.mjs from design/tokens.json — do not edit. */\n';

const vars = (o, prefix, unit = '') =>
  Object.entries(o).map(([k, v]) => `  --${prefix}${k}: ${typeof v === 'number' ? v + unit : v};`).join('\n');
const colors = (o) => vars(o, '');

// F10.2 accents on web: the same four colours per mode; teal is the base, so it has no rule
const accentCss = Object.entries(t.accent).filter(([k]) => !k.startsWith('$') && k !== 'teal').map(([k, v]) =>
  `:root:not([data-theme='light'])[data-accent='${k}'] {\n${colors(v.dark)}\n}\n:root[data-theme='light'][data-accent='${k}'] {\n${colors(v.light)}\n}`).join('\n');
// F10.2 text size and density: the type and space steps scaled (Android: 1.15 and 1.3; compact 0.75)
const scaled = (o, f, prefix) => Object.entries(o).map(([k, v]) => `  --${prefix}${k}: ${Math.round(v * f * 10) / 10}px;`).join('\n');
const scaleCss = `:root[data-text='large'] {\n${scaled(t.size, 1.15, 'fs-')}\n}\n:root[data-text='larger'] {\n${scaled(t.size, 1.3, 'fs-')}\n}\n:root[data-density='compact'] {\n${scaled(t.space, 0.75, 's-')}\n}\n`;

const css = `${header}
:root {
${colors(t.color.dark)}
${vars(t.radius, 'r-', 'px')}
${vars(t.space, 's-', 'px')}
${vars(t.size, 'fs-', 'px')}
  --font-body: ${t.font.body};
  --font-display: ${t.font.display};
  --font-mono: ${t.font.mono};
  --t-fast: ${t.motion.fast}ms;
  --t-base: ${t.motion.base}ms;
  --t-slow: ${t.motion.slow}ms;
  --ease: ${t.motion.ease};
  --shadow-pop: ${t.shadow.pop};
  --shadow-menu: ${t.shadow.menu};
  --scrim: ${t.shadow.scrim};
  color-scheme: dark;
}
:root[data-theme='light'] {
${colors(t.color.light)}
  color-scheme: light;
}
${accentCss}
${scaleCss}`;
const cssPath = join(root, 'web/src/lib/design/tokens.css');
emit(cssPath, css);

const kname = (k) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const kcolor = (h) => `Color(0xFF${h.slice(1).toUpperCase()})`;
const palette = (name, o) =>
  `    val ${name} = ChorusPalette(\n${Object.entries(o).map(([k, v]) => `        ${kname(k)} = ${kcolor(v)},`).join('\n')}\n    )`;
// F10.2 accents (Android only so far): each swaps the four accent colours of a palette
const accents = Object.entries(t.accent).filter(([k]) => !k.startsWith('$'));
const tones = (o) => `AccentTones(${Object.entries(o).map(([k, v]) => `${kname(k)} = ${kcolor(v)}`).join(', ')})`;
const kt = `// Generated by scripts/gen-tokens.mjs from design/tokens.json — do not edit.
package garden.vayne.chorus.designsystem

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

data class ChorusPalette(
${Object.keys(t.color.light).map((k) => `    val ${kname(k)}: Color,`).join('\n')}
)

data class AccentTones(${Object.keys(accents[0][1].light).map((k) => `val ${kname(k)}: Color`).join(', ')})

enum class ChorusAccent(val label: String, val light: AccentTones, val dark: AccentTones) {
${accents.map(([k, v]) => `    ${k[0].toUpperCase() + k.slice(1)}("${k[0].toUpperCase() + k.slice(1)}",\n        ${tones(v.light)},\n        ${tones(v.dark)}),`).join('\n')}
}

object Tokens {
${palette('Light', t.color.light)}
${palette('Dark', t.color.dark)}
${Object.entries(t.radius).map(([k, v]) => `    val radius${k[0].toUpperCase() + k.slice(1)} = ${v}.dp`).join('\n')}
${Object.entries(t.space).map(([k, v]) => `    val space${k} = ${v}.dp`).join('\n')}
    const val motionFast = ${t.motion.fast}
    const val motionBase = ${t.motion.base}
    const val motionSlow = ${t.motion.slow}
}
`;
const ktDir = join(root, 'android/designsystem/src/main/kotlin/garden/vayne/chorus/designsystem');
if (existsSync(join(root, 'android'))) {
  emit(join(ktDir, 'Tokens.kt'), kt);
}
if (stale.length) {
  console.error(`tokens out of date (run node scripts/gen-tokens.mjs): ${stale.join(', ')}`);
  process.exit(1);
}
console.log(check ? 'tokens up to date' : 'tokens written');
